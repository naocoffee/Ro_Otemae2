  function hishLine(spot, lay, spots) {
    const k = kamaCenter(lay);
    switch (spot) {
      case "hFuta": { const f = spots.futa; return [[f[0], f[1] - 3], [f[0] - 24, f[1] + 38]]; }
      case "hKama": {
        const dx = (spots.host[0] - k[0]), dy = (spots.host[1] - k[1]);
        const len = Math.hypot(dx, dy);
        return [[k[0], k[1] - 2], [k[0] + dx / len * 58, k[1] + dy / len * 58]];
      }
      case "hKen": { const n = spots.ken; return [[n[0] + 2, n[1] - 4], [n[0] + 30, n[1] - 42]]; }
      case "tanaH": return [[70, 26], [132, 26]];
      case "inTate": { const t = spots.naShaku; return [[t[0], t[1] - 2], [t[0] + 6, t[1] - 38]]; }
      default: return null;
    }
  }

  function buildItems(step) {
    const base = PRESETS[step.sc] || {};
    const items = Object.assign({}, base);
    if (step.o && step.o.o) {
      Object.keys(step.o.o).forEach(function (k) {
        if (step.o.o[k] === null) delete items[k]; else items[k] = step.o.o[k];
      });
    }
    return items;
  }

  function esc(s) {
    return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
  }

